"""Durable, sanitized benchmark checkpoints. Never stores requests/credentials.
Writes are outside timed database/HTTP sections; staging wall time may include
checkpoint I/O. Journal files remain available after assertion/timeout/process exit.
"""
import json,os,time
from pathlib import Path

class Journal:
    FIELDS={'case','mode','stage','trial','variant','records','parts','part','changes',
            'measurement','profile','profile_partial','outcome','sqlstate','http_status',
            'rollback_verified','replay_equal','integrity_equal','sequence','hash',
            'budget','capacity_blocked','completed','reason','accepted','label'}
    def __init__(self,path,case):
        self.path=Path(path);self.path.parent.mkdir(parents=True,exist_ok=True)
        self.data={'case':case,'hosted_executed':False,'events':[]}
        self.start=time.monotonic()
    def event(self,**fields):
        assert set(fields)<=self.FIELDS,'Non-sanitized benchmark field'
        # Measurement/profile values are generated by the benchmark, never raw HTTP/SQL bodies.
        self.data['events'].append(dict(elapsed_ms=round((time.monotonic()-self.start)*1000,3),**fields))
        temporary=self.path.with_name(self.path.name+'.'+str(os.getpid())+'.tmp')
        fd=os.open(temporary,os.O_CREAT|os.O_EXCL|os.O_WRONLY,0o600)
        try:
            with os.fdopen(fd,'w')as out:
                json.dump(self.data,out,indent=2,ensure_ascii=False);out.write('\n');out.flush();os.fsync(out.fileno())
            os.replace(temporary,self.path)
            directory=os.open(self.path.parent,os.O_RDONLY)
            try:os.fsync(directory)
            finally:os.close(directory)
        finally:
            temporary.unlink(missing_ok=True)
